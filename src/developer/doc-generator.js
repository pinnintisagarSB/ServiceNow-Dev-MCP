/**
 * ServiceNow Documentation Generator
 *
 * Auto-generates human-readable documentation for:
 *  - Script Includes (API reference)
 *  - Business Rules (what they do, when, conditions)
 *  - Tables (field catalogue, relationships, ACLs)
 *  - Applications (full component inventory)
 *  - Integration points (REST APIs, outbound calls)
 *
 * Output formats: Markdown, Confluence wiki markup, or plain text.
 */

export class DocGenerator {

  // ══════════════════════════════════════════════════════════════════════════
  // Script Include → Markdown API docs
  // ══════════════════════════════════════════════════════════════════════════
  documentScriptInclude({ name, script, description, client_callable }) {
    const methods = this._parseMethods(script);

    const methodDocs = methods.map(m => `
### \`${m.name}(${m.params})\`

${m.docComment ?? '_No description provided._'}

**Returns:** ${m.returnType ?? 'Object'}

\`\`\`javascript
var si = new ${name}();
var result = si.${m.name}(${m.exampleInput ?? '{}' });
if (result.success) {
    // use result.data
} else {
    gs.error(result.error);
}
\`\`\`
`).join('\n');

    return `
# ${name}

${description ?? '_No description._'}

| Property | Value |
|---|---|
| Type | Script Include |
| Client Callable | ${client_callable ? '✅ Yes' : '❌ No'} |
| Generated | ${new Date().toISOString().split('T')[0]} |

## Usage

\`\`\`javascript
var helper = new ${name}();
var result = helper.methodName(params);
\`\`\`

## Methods

${methodDocs || '_No public methods found._'}

---
_Generated by ServiceNow Developer MCP_
`.trim();
  }

  // ══════════════════════════════════════════════════════════════════════════
  // Business Rule → Markdown docs
  // ══════════════════════════════════════════════════════════════════════════
  documentBusinessRule({ name, table, when, events = [], condition, script, description }) {
    const riskFlags = [];
    if (!condition)                           riskFlags.push('⚠️ No condition set — fires on every matching event');
    if (/new GlideRecord/.test(script ?? '')) riskFlags.push('⚠️ Contains GlideRecord query — check for missing setLimit()');
    if (/RESTMessageV2/.test(script ?? ''))   riskFlags.push('⚠️ Contains REST call — ensure this is async');

    return `
# Business Rule: ${name}

${description ?? '_No description._'}

## Metadata

| Property | Value |
|---|---|
| Table | \`${table}\` |
| When | ${when} |
| Events | ${events.join(', ') || 'none'} |
| Condition | \`${condition || '(none — always fires)'}\` |

## Risk Flags

${riskFlags.length ? riskFlags.join('\n') : '✅ No obvious risks detected.'}

## Script Preview

\`\`\`javascript
${(script ?? '').substring(0, 800)}${(script ?? '').length > 800 ? '\n// ... (truncated)' : ''}
\`\`\`

---
_Generated by ServiceNow Developer MCP_
`.trim();
  }

  // ══════════════════════════════════════════════════════════════════════════
  // Table schema → Markdown field catalogue
  // ══════════════════════════════════════════════════════════════════════════
  documentTable({ table, info, fields = [], business_rules = [], acls = [], relationships = [] }) {
    const fieldTable = fields.slice(0, 50).map(f =>
      `| \`${f.field}\` | ${f.label} | ${f.type} | ${f.reference_to ? `→ \`${f.reference_to}\`` : ''} | ${f.mandatory ? '✅' : ''} | ${f.read_only ? '🔒' : ''} |`
    ).join('\n');

    const brTable = business_rules.map(br =>
      `| ${br.name} | ${br.when} | ${br.events.join(', ')} | \`${br.condition || '(always)'}\` |`
    ).join('\n');

    const aclTable = acls.map(a =>
      `| ${a.name} | ${a.operation} | ${a.type} | ${a.roles} |`
    ).join('\n');

    return `
# Table: ${table}

**Label:** ${info?.label ?? table}
**Parent:** ${info?.parent_table ?? '(none)'}
**Scope:** ${info?.scope ?? 'global'}

## Field Catalogue (${fields.length} fields)

| Field | Label | Type | Reference | Mandatory | Read Only |
|---|---|---|---|---|---|
${fieldTable || '_No fields found._'}
${fields.length > 50 ? `\n_…and ${fields.length - 50} more fields._` : ''}

## Business Rules (${business_rules.length})

| Name | When | Events | Condition |
|---|---|---|---|
${brTable || '_None._'}

## ACLs (${acls.length})

| Name | Operation | Type | Roles |
|---|---|---|---|
${aclTable || '_None._'}

## Incoming Relationships (${relationships.length})

${relationships.map(r => `- \`${r.from_table}.${r.field}\` references this table`).join('\n') || '_None._'}

---
_Generated by ServiceNow Developer MCP_
`.trim();
  }

  // ══════════════════════════════════════════════════════════════════════════
  // REST API → Markdown API reference
  // ══════════════════════════════════════════════════════════════════════════
  documentRestApi({ name, apiPath, verb, description, requiresAuth, script }) {
    const params = this._extractRestParams(script ?? '');

    return `
# REST API: ${name}

${description ?? '_No description._'}

## Endpoint

\`\`\`
${verb} /api/${apiPath}
\`\`\`

| Property | Value |
|---|---|
| Verb | \`${verb}\` |
| Path | \`/api/${apiPath}\` |
| Authentication | ${requiresAuth ? '✅ Required' : '❌ Public'} |

## Parameters

${params.length ? params.map(p => `- **\`${p}\`** — (string)`).join('\n') : '_None detected._'}

## Response Format

\`\`\`json
{
  "status":  "success | error",
  "message": "Human-readable message",
  "data":    {}
}
\`\`\`

## Error Codes

| Code | Meaning |
|---|---|
| 400 | Missing or invalid parameters |
| 401 | Authentication required |
| 403 | Insufficient permissions |
| 500 | Server error |

---
_Generated by ServiceNow Developer MCP_
`.trim();
  }

  // ══════════════════════════════════════════════════════════════════════════
  // Application inventory → Markdown overview
  // ══════════════════════════════════════════════════════════════════════════
  documentApplication({ appName, scope, components }) {
    const sections = Object.entries(components ?? {}).map(([type, items]) => `
## ${type} (${items.length})

${items.map(i => `- **${i.name}**${i.table ? ` — ${i.table}` : ''}${i.description ? `: ${i.description}` : ''}`).join('\n') || '_None._'}
`).join('\n');

    return `
# Application: ${appName}

**Scope:** ${scope ?? 'unknown'}
**Generated:** ${new Date().toISOString().split('T')[0]}

${sections}

---
_Generated by ServiceNow Developer MCP_
`.trim();
  }

  // ── Helpers ─────────────────────────────────────────────────────────────────
  _parseMethods(script) {
    if (!script) return [];
    const methods = [];
    const regex = /\/\*\*([\s\S]*?)\*\/\s*(\w+)\s*:\s*function\s*\(([^)]*)\)/g;
    let match;
    while ((match = regex.exec(script)) !== null) {
      methods.push({
        name:       match[2],
        params:     match[3].trim(),
        docComment: match[1].replace(/\s*\*\s*/g, ' ').trim(),
      });
    }
    // Fallback — no JSDoc
    if (!methods.length) {
      const simple = /(\w+)\s*:\s*function\s*\(([^)]*)\)/g;
      while ((match = simple.exec(script)) !== null) {
        if (['initialize', 'type'].includes(match[1])) continue;
        methods.push({ name: match[1], params: match[2].trim(), docComment: null });
      }
    }
    return methods;
  }

  _extractRestParams(script) {
    const matches = [...script.matchAll(/request\.queryParams\.(\w+)/g)];
    return [...new Set(matches.map(m => m[1]))];
  }
}
