/**
 * Salesforce Artifact Builder for Bidirectional Integrations
 *
 * Salesforce requires async callouts and Named Credentials — we can't
 * create Apex classes via API, but we can:
 *   1. Create Named Credential via Metadata API (or generate the XML)
 *   2. Generate the Apex Queueable callout class (ready to paste/deploy)
 *   3. Generate the Apex Trigger (ready to paste/deploy)
 *   4. Generate the Salesforce Flow XML (for Flow-based trigger)
 *   5. Generate a Platform Event definition (for event-driven pattern)
 *   6. Create the Connected App via REST (if SF connector supports it)
 *   7. Generate step-by-step setup instructions
 */

import { logger } from '../utils/logger.js';

export class SFArtifactBuilder {
  constructor(sf) {
    this.sf = sf;
  }

  // ══════════════════════════════════════════════════════════════════════════
  // 1. Named Credential metadata (XML to deploy or create via Setup UI)
  // ══════════════════════════════════════════════════════════════════════════
  generateNamedCredentialXml(plan, targetUrl, username, password) {
    const prefix = plan.meta.prefix;
    const name   = `${prefix}_target_credential`;

    return {
      named_credential_name: name,
      metadata_api_name:     name,
      xml: `<?xml version="1.0" encoding="UTF-8"?>
<NamedCredential xmlns="http://soap.sforce.com/2006/04/metadata">
    <label>${name}</label>
    <name>${name}</name>
    <endpoint>${targetUrl}</endpoint>
    <protocol>Password</protocol>
    <username>${username ?? 'your-api-username'}</username>
    <password>${password ? '[SET IN SETUP UI]' : 'your-api-password'}</password>
    <allowMergeFieldsInBody>true</allowMergeFieldsInBody>
    <allowMergeFieldsInHeader>true</allowMergeFieldsInHeader>
    <generateAuthorizationHeader>true</generateAuthorizationHeader>
</NamedCredential>`,
      setup_instructions: [
        'Go to Setup → Security → Named Credentials → New',
        `Label: ${name}`,
        `URL: ${targetUrl}`,
        'Identity Type: Named Principal',
        'Authentication Protocol: Password Authentication',
        'Enter your API username and password',
        'Allow Merge Fields in HTTP Body: Yes',
        'Save and test the connection',
      ],
    };
  }

  // ══════════════════════════════════════════════════════════════════════════
  // 2. Apex Queueable class (async callout — required for callouts from triggers)
  // ══════════════════════════════════════════════════════════════════════════
  generateApexCalloutClass(plan) {
    const prefix     = plan.meta.prefix;
    const sfIsA      = plan.meta.platformA === 'salesforce';
    const sfTable    = sfIsA ? plan.meta.tableA : plan.meta.tableB;
    const target     = sfIsA ? plan.meta.platformB : plan.meta.platformA;
    const fieldMaps  = plan.meta.fieldMappings;
    const credName   = `${prefix}_target_credential`;
    const className  = `${this._toClassName(prefix)}SyncCallout`;

    const fieldBuildLines = Object.entries(fieldMaps).map(([sfField, extField]) => {
      return `        payload.put('${extField}', String.valueOf(record.get('${sfField}')));`;
    }).join('\n');

    const code = `/**
 * ${className}
 * Async callout to ${target} — enqueued from a trigger or Flow.
 * Generated by SN Migration Agent.
 */
public class ${className} implements Queueable, Database.AllowsCallouts {

    private String recordId;
    private String objectType;
    private String action; // 'create_or_update' | 'delete'

    public ${className}(String recordId, String objectType, String action) {
        this.recordId   = recordId;
        this.objectType = objectType;
        this.action     = action;
    }

    public void execute(QueueableContext ctx) {
        // ── Load the record ────────────────────────────────────────────────
        SObject record;
        try {
            record = Database.query(
                'SELECT Id, ' + getFieldList() + ' FROM ' + objectType +
                ' WHERE Id = :recordId LIMIT 1'
            );
        } catch (Exception e) {
            System.debug(LoggingLevel.ERROR, '${className}: Failed to load record ' + recordId + ': ' + e.getMessage());
            return;
        }

        // ── Build payload ──────────────────────────────────────────────────
        Map<String, Object> payload = new Map<String, Object>();
        payload.put('_sf_id',      recordId);
        payload.put('_sf_object',  objectType);
        payload.put('_action',     action);
${fieldBuildLines}

        // ── Get correlation ID if record was previously synced ─────────────
        // Store correlation in a custom field on the object: ${prefix}__Ext_Id__c
        String externalId = (String) record.get('${prefix}__Ext_Id__c');
        if (String.isNotBlank(externalId)) payload.put('_external_id', externalId);

        // ── Make the callout ───────────────────────────────────────────────
        String endpoint = 'callout:${credName}/sync';
        HttpRequest req = new HttpRequest();
        req.setEndpoint(endpoint);
        req.setMethod('POST');
        req.setHeader('Content-Type', 'application/json');
        req.setHeader('X-Integration-Source', 'salesforce');
        req.setHeader('X-Prefix', '${prefix}');
        req.setBody(JSON.serialize(payload));
        req.setTimeout(30000);

        try {
            Http http = new Http();
            HttpResponse res = http.send(req);

            if (res.getStatusCode() >= 200 && res.getStatusCode() < 300) {
                Map<String, Object> respBody = (Map<String, Object>) JSON.deserializeUntyped(res.getBody());
                String extId = (String) respBody.get('id');
                if (extId == null) extId = (String) respBody.get('key');
                if (extId == null) extId = (String) respBody.get('sys_id');

                // Store the external ID back on the SF record for future syncs
                if (String.isNotBlank(extId) && String.isBlank(externalId)) {
                    SObject toUpdate = record.getSObjectType().newSObject(recordId);
                    toUpdate.put('${prefix}__Ext_Id__c', extId);
                    // Suppress trigger re-fire: use system context or a bypass flag
                    // TriggerBypass__c.${prefix}__Bypass__c = true  ← set before update
                    Database.update(toUpdate, false);
                }
                System.debug('${className}: Sync OK — SF ' + recordId + ' → ${target} ' + extId);
            } else {
                System.debug(LoggingLevel.ERROR, '${className}: HTTP ' + res.getStatusCode() + ' ' + res.getBody());
                // TODO: write to an error custom object for retry
            }
        } catch (Exception e) {
            System.debug(LoggingLevel.ERROR, '${className}: Callout exception: ' + e.getMessage());
        }
    }

    private String getFieldList() {
        List<String> fields = new List<String>{ 'Id', '${prefix}__Ext_Id__c' };
        // Add all mapped SF fields:
${Object.keys(fieldMaps).map(f => `        fields.add('${f}');`).join('\n')}
        return String.join(fields, ', ');
    }
}`;

    return { class_name: className, apex_code: code };
  }

  // ══════════════════════════════════════════════════════════════════════════
  // 3. Apex Trigger
  // ══════════════════════════════════════════════════════════════════════════
  generateApexTrigger(plan) {
    const prefix     = plan.meta.prefix;
    const sfIsA      = plan.meta.platformA === 'salesforce';
    const sfTable    = sfIsA ? plan.meta.tableA : plan.meta.tableB;
    const trigPlan   = sfIsA ? plan.outbound_a_to_b?.trigger : plan.outbound_b_to_a?.trigger;
    const events     = trigPlan?.events ?? ['record_created', 'record_updated'];
    const calloutCls = `${this._toClassName(prefix)}SyncCallout`;
    const trigName   = `${this._toClassName(prefix)}SyncTrigger`;

    const sfEvents = [];
    if (events.includes('record_created')) sfEvents.push('after insert');
    if (events.includes('record_updated')) sfEvents.push('after update');
    if (events.includes('record_deleted')) sfEvents.push('after delete');
    if (!sfEvents.length) sfEvents.push('after insert', 'after update');

    const triggerCode = `/**
 * ${trigName}
 * Fires async sync callout to ${plan.meta.platformA === 'salesforce' ? plan.meta.platformB : plan.meta.platformA}
 * on ${sfTable} changes. Generated by SN Migration Agent.
 */
trigger ${trigName} on ${sfTable} (${sfEvents.join(', ')}) {

    // ── Bypass check (prevents infinite loop on inbound sync updates) ──────
    // Set ${prefix}__SyncBypass__c = true on the user/session when updating from inbound sync
    if (${prefix}__TriggerBypass__mdt.getInstance('${prefix}')?.${prefix}__Active__c == true) return;

    List<String> recordIds = new List<String>();
    List<SObject> records  = Trigger.isDelete ? Trigger.old : Trigger.new;
    String action          = Trigger.isDelete ? 'delete' : 'create_or_update';

    for (SObject rec : records) {
        recordIds.add((String) rec.get('Id'));
    }

    // Enqueue async callouts (one per record — adjust for bulk if needed)
    for (String recId : recordIds) {
        System.enqueueJob(new ${calloutCls}(recId, '${sfTable}', action));
    }
}`;

    return { trigger_name: trigName, apex_code: triggerCode };
  }

  // ══════════════════════════════════════════════════════════════════════════
  // 4. Inbound REST handler (Salesforce receives calls from other platform)
  //    Implemented as a Salesforce Connected REST Endpoint via a Flow or Apex REST
  // ══════════════════════════════════════════════════════════════════════════
  generateInboundApexRest(plan) {
    const prefix   = plan.meta.prefix;
    const sfTable  = plan.meta.platformA === 'salesforce' ? plan.meta.tableA : plan.meta.tableB;
    const src      = plan.meta.platformA === 'salesforce' ? plan.meta.platformB : plan.meta.platformA;
    const fieldMappings = plan.meta.fieldMappings;
    const className = `${this._toClassName(prefix)}InboundRest`;

    // Inbound maps: external field → SF field
    const sfIsA     = plan.meta.platformA === 'salesforce';
    const fieldAssignLines = Object.entries(fieldMappings).map(([aField, bField]) => {
      const sfField  = sfIsA ? aField : bField;
      const extField = sfIsA ? bField : aField;
      return `        if (payload.containsKey('${extField}')) rec.put('${sfField}', payload.get('${extField}'));`;
    }).join('\n');

    const code = `/**
 * ${className}
 * Salesforce Apex REST endpoint — receives sync calls from ${src}.
 * URL: /services/apexrest/${prefix}/sync
 * Generated by SN Migration Agent.
 */
@RestResource(urlMapping='/${prefix}/sync/*')
global class ${className} {

    @HttpPost
    global static Map<String, Object> doPost() {
        RestRequest  req  = RestContext.request;
        RestResponse resp = RestContext.response;

        Map<String, Object> result = new Map<String, Object>();

        try {
            Map<String, Object> payload =
                (Map<String, Object>) JSON.deserializeUntyped(req.requestBody.toString());

            String externalId = (String) payload.get('_external_id');
            String sfId       = (String) payload.get('_sf_id');

            // ── Find or create the SF record ───────────────────────────────
            SObject rec;
            Boolean isNew = false;

            if (String.isNotBlank(sfId)) {
                List<SObject> found = Database.query(
                    'SELECT Id FROM ${sfTable} WHERE Id = :sfId LIMIT 1'
                );
                if (!found.isEmpty()) rec = found[0];
            }

            if (rec == null && String.isNotBlank(externalId)) {
                List<SObject> found = Database.query(
                    'SELECT Id FROM ${sfTable} WHERE ${prefix}__Ext_Id__c = :externalId LIMIT 1'
                );
                if (!found.isEmpty()) rec = found[0];
            }

            if (rec == null) {
                rec   = Schema.getGlobalDescribe().get('${sfTable}').newSObject();
                isNew = true;
            }

            // ── Loop prevention ────────────────────────────────────────────
            // Set bypass flag so our trigger doesn't fire back
            // ${prefix}__TriggerBypass__mdt — set via test or bypass mechanism

            // ── Apply field mappings ───────────────────────────────────────
${fieldAssignLines}
            if (String.isNotBlank(externalId)) rec.put('${prefix}__Ext_Id__c', externalId);

            // ── Save ───────────────────────────────────────────────────────
            if (isNew) {
                Database.insert(rec, false);
            } else {
                Database.update(rec, false);
            }

            resp.statusCode = 200;
            result.put('status', 'ok');
            result.put('sf_id',  (String) rec.get('Id'));
            result.put('action', isNew ? 'created' : 'updated');

        } catch (Exception e) {
            resp.statusCode = 400;
            result.put('status',  'error');
            result.put('message', e.getMessage());
        }

        return result;
    }
}`;

    return {
      class_name: className,
      apex_code:  code,
      endpoint:   `/services/apexrest/${prefix}/sync`,
    };
  }

  // ══════════════════════════════════════════════════════════════════════════
  // 5. Collect all generated artifacts and instructions
  // ══════════════════════════════════════════════════════════════════════════
  buildAll(plan, opts = {}) {
    const sfInvolved = plan.meta.platformA === 'salesforce' || plan.meta.platformB === 'salesforce';
    if (!sfInvolved) return {};

    logger.header(`Building Salesforce artifacts for ${plan.meta.prefix}`);

    const namedCred    = this.generateNamedCredentialXml(plan, opts.targetUrl ?? '<target-url>');
    const calloutClass = this.generateApexCalloutClass(plan);
    const trigger      = this.generateApexTrigger(plan);
    const inboundRest  = this.generateInboundApexRest(plan);
    const instructions = this._deploymentInstructions(plan, namedCred, calloutClass, trigger, inboundRest);

    logger.ok(`Salesforce artifacts generated for ${plan.meta.prefix}`);

    return {
      named_credential:    namedCred,
      apex_callout_class:  calloutClass,
      apex_trigger:        trigger,
      inbound_apex_rest:   inboundRest,
      deployment_instructions: instructions,
    };
  }

  _deploymentInstructions(plan, namedCred, callout, trigger, inbound) {
    return [
      '═══ Salesforce Deployment Steps ═══',
      '',
      '1. CREATE NAMED CREDENTIAL',
      '   Setup → Security → Named Credentials → New',
      `   Use the XML/values in named_credential`,
      '',
      '2. CREATE CUSTOM FIELD on ' + (plan.meta.platformA === 'salesforce' ? plan.meta.tableA : plan.meta.tableB),
      `   Field Name: ${plan.meta.prefix}__Ext_Id__c  (Text, 255)`,
      '   This stores the external platform ID for correlation.',
      '',
      '3. DEPLOY APEX CLASSES (Developer Console or VS Code + SFDX)',
      `   a. Create new Apex class: ${callout.class_name}`,
      '      Paste code from apex_callout_class.apex_code',
      `   b. Create new Apex class: ${inbound.class_name}`,
      '      Paste code from inbound_apex_rest.apex_code',
      '',
      '4. DEPLOY APEX TRIGGER',
      `   Create new Apex trigger: ${trigger.trigger_name}`,
      '   Paste code from apex_trigger.apex_code',
      '',
      '5. CREATE CUSTOM METADATA TYPE for trigger bypass',
      '   Setup → Custom Metadata Types → New',
      `   Label: ${plan.meta.prefix} Trigger Bypass`,
      `   Name: ${plan.meta.prefix}__TriggerBypass__mdt`,
      '   Add boolean field: Active__c',
      '',
      '6. ALLOW CALLOUTS',
      '   Setup → Remote Site Settings → New',
      `   Remote Site URL: (your target platform base URL)`,
      '',
      '7. TEST THE INTEGRATION',
      '   a. Create a test record in Salesforce and verify it appears in the target platform',
      '   b. Update the target platform record and verify it updates in Salesforce',
      '   c. Check for duplicate records (confirm loop prevention is working)',
      '',
      `Inbound endpoint: ${inbound.endpoint}`,
      '   Register this URL as the webhook/callback endpoint in the partner platform.',
    ];
  }

  _toClassName(prefix) {
    return prefix.split('_').map(p => p.charAt(0).toUpperCase() + p.slice(1)).join('');
  }
}
